"""
COMP 3005 - Assignment 3, Question 1
Database Interaction with PostgreSQL and Application Programming

A small command-line application that connects to a PostgreSQL database and
performs CRUD (Create, Read, Update, Delete) operations on the `students` table.

The four required functions keep the exact names used in the assignment:
    getAllStudents()                                              -> Read
    addStudent(first_name, last_name, email, enrollment_date)     -> Create
    updateStudentEmail(student_id, new_email)                     -> Update
    deleteStudent(student_id)                                     -> Delete

Usage (run from the repository root, see README.md for setup):
    python app/students_app.py                     # interactive menu
    python app/students_app.py list
    python app/students_app.py add Alice Brown alice.brown@example.com 2023-09-03
    python app/students_app.py update-email 4 alice.b@example.com
    python app/students_app.py delete 4
"""

import argparse
import os
import sys
from contextlib import closing
from datetime import date

import psycopg2
from psycopg2 import errors


# -----------------------------------------------------------------------------
# Database connection
# -----------------------------------------------------------------------------
# Connection settings come from environment variables, so no password is
# hard-coded in the source. The defaults match a typical local PostgreSQL setup.
DB_SETTINGS = {
    "host": os.getenv("DB_HOST", "localhost"),
    "port": os.getenv("DB_PORT", "5432"),
    "dbname": os.getenv("DB_NAME", "students_db"),
    "user": os.getenv("DB_USER", "postgres"),
    "password": os.getenv("DB_PASSWORD", "postgres"),
}


def get_connection():
    """Open and return a new connection to the PostgreSQL database."""
    return psycopg2.connect(**DB_SETTINGS)


# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------
def parse_date(value):
    """Turn a 'YYYY-MM-DD' string into a date object.

    Empty input (or None) means "no enrollment date", which is stored as NULL.
    Raises ValueError if the text is not a valid date.
    """
    if value is None or isinstance(value, date):
        return value
    text = str(value).strip()
    if text == "":
        return None
    return date.fromisoformat(text)


def print_students(rows):
    """Print student rows as an aligned text table."""
    if not rows:
        print("The students table is empty.")
        return

    headers = ("student_id", "first_name", "last_name", "email", "enrollment_date")
    # Convert every value to text (NULL becomes an empty string) so the
    # width of each column can be measured.
    table = [headers] + [tuple("" if v is None else str(v) for v in row) for row in rows]
    widths = [max(len(row[i]) for row in table) for i in range(len(headers))]

    for index, row in enumerate(table):
        print("  ".join(value.ljust(widths[i]) for i, value in enumerate(row)))
        if index == 0:  # underline the header row
            print("  ".join("-" * w for w in widths))


# -----------------------------------------------------------------------------
# Required functions (CRUD)
# -----------------------------------------------------------------------------
def getAllStudents():
    """READ: retrieve and display every record in the students table.

    Returns the rows as a list of tuples.
    """
    query = """
        SELECT student_id, first_name, last_name, email, enrollment_date
        FROM students
        ORDER BY student_id;
    """
    # closing() makes sure the connection is closed even if an error occurs;
    # the cursor is closed automatically by its own "with" block.
    with closing(get_connection()) as conn, conn.cursor() as cur:
        cur.execute(query)
        rows = cur.fetchall()

    print_students(rows)
    return rows


def addStudent(first_name, last_name, email, enrollment_date=None):
    """CREATE: insert a new student record.

    enrollment_date can be a 'YYYY-MM-DD' string, a date object, or None.
    Returns the new student_id generated by the database, or None on error.
    """
    # Validate the input in Python first so the user gets a clear message.
    first_name, last_name, email = (str(v).strip() for v in (first_name, last_name, email))
    if not first_name or not last_name or not email:
        print("Error: first name, last name and email are all required.")
        return None
    try:
        enrollment_date = parse_date(enrollment_date)
    except ValueError:
        print(f"Error: '{enrollment_date}' is not a valid date. Use the format YYYY-MM-DD.")
        return None

    # The %s placeholders let psycopg2 pass the values safely (no SQL injection).
    # RETURNING gives back the student_id that SERIAL generated for the new row.
    query = """
        INSERT INTO students (first_name, last_name, email, enrollment_date)
        VALUES (%s, %s, %s, %s)
        RETURNING student_id;
    """
    with closing(get_connection()) as conn:
        try:
            with conn.cursor() as cur:
                cur.execute(query, (first_name, last_name, email, enrollment_date))
                new_id = cur.fetchone()[0]
            conn.commit()  # make the insert permanent
        except errors.UniqueViolation:
            # The UNIQUE constraint on email rejected the row.
            conn.rollback()
            print(f"Error: a student with the email '{email}' already exists.")
            return None

    print(f"Added {first_name} {last_name} with student_id {new_id}.")
    return new_id


def updateStudentEmail(student_id, new_email):
    """UPDATE: change the email address of the student with the given student_id.

    Returns True if a row was updated, False otherwise.
    """
    new_email = str(new_email).strip()
    if not new_email:
        print("Error: the new email cannot be empty.")
        return False

    query = "UPDATE students SET email = %s WHERE student_id = %s;"
    with closing(get_connection()) as conn:
        try:
            with conn.cursor() as cur:
                cur.execute(query, (new_email, student_id))
                updated = cur.rowcount  # number of rows the UPDATE changed
            conn.commit()  # make the update permanent
        except errors.UniqueViolation:
            # Another student already has this email.
            conn.rollback()
            print(f"Error: the email '{new_email}' is already used by another student.")
            return False

    if updated == 0:
        print(f"No student found with student_id {student_id}. Nothing was updated.")
        return False

    print(f"Updated the email of student {student_id} to {new_email}.")
    return True


def deleteStudent(student_id):
    """DELETE: remove the student with the given student_id.

    Returns True if a row was deleted, False otherwise.
    """
    query = "DELETE FROM students WHERE student_id = %s;"
    with closing(get_connection()) as conn:
        with conn.cursor() as cur:
            cur.execute(query, (student_id,))
            deleted = cur.rowcount  # number of rows the DELETE removed
        conn.commit()  # make the delete permanent

    if deleted == 0:
        print(f"No student found with student_id {student_id}. Nothing was deleted.")
        return False

    print(f"Deleted the student with student_id {student_id}.")
    return True


