# User interface
# -----------------------------------------------------------------------------
def read_int(prompt):
    """Ask for a whole number; return None if the input is not a number."""
    text = input(prompt).strip()
    if text.isdigit():
        return int(text)
    print("Please enter a whole number.")
    return None


def interactive_menu():
    """Text menu that lets the user run each function one after another."""
    while True:
        print("\n=== Students database ===")
        print("1) Show all students")
        print("2) Add a student")
        print("3) Update a student's email")
        print("4) Delete a student")
        print("5) Exit")
        choice = input("Choose an option (1-5): ").strip()

        if choice == "1":
            getAllStudents()
        elif choice == "2":
            first_name = input("First name: ")
            last_name = input("Last name: ")
            email = input("Email: ")
            enrollment_date = input("Enrollment date (YYYY-MM-DD, leave blank for none): ")
            addStudent(first_name, last_name, email, enrollment_date)
        elif choice == "3":
            student_id = read_int("Student ID: ")
            if student_id is not None:
                updateStudentEmail(student_id, input("New email: "))
        elif choice == "4":
            student_id = read_int("Student ID: ")
            if student_id is not None:
                deleteStudent(student_id)
        elif choice == "5":
            print("Goodbye.")
            break
        else:
            print("Please choose an option from 1 to 5.")


def build_parser():
    """Define the command-line commands, one per required function."""
    parser = argparse.ArgumentParser(
        description="CRUD operations on the students table (COMP 3005 A3 Q1). "
                    "Run without a command to open the interactive menu."
    )
    commands = parser.add_subparsers(dest="command")

    commands.add_parser("list", help="show all students (getAllStudents)")

    add = commands.add_parser("add", help="add a new student (addStudent)")
    add.add_argument("first_name")
    add.add_argument("last_name")
    add.add_argument("email")
    add.add_argument("enrollment_date", nargs="?", default=None,
                     help="optional, format YYYY-MM-DD")

    update = commands.add_parser("update-email", help="change a student's email (updateStudentEmail)")
    update.add_argument("student_id", type=int)
    update.add_argument("new_email")

    delete = commands.add_parser("delete", help="delete a student (deleteStudent)")
    delete.add_argument("student_id", type=int)

    return parser


def main():
    """Entry point: run the requested command, or the menu if none is given."""
    args = build_parser().parse_args()
    try:
        if args.command is None:
            interactive_menu()
        elif args.command == "list":
            getAllStudents()
        elif args.command == "add":
            addStudent(args.first_name, args.last_name, args.email, args.enrollment_date)
        elif args.command == "update-email":
            updateStudentEmail(args.student_id, args.new_email)
        elif args.command == "delete":
            deleteStudent(args.student_id)
    except psycopg2.OperationalError as exc:
        # Raised when PostgreSQL can't be reached (server stopped, wrong
        # password, wrong port, database not created yet, ...).
        print("Could not connect to PostgreSQL. Check that the server is running "
              "and that the DB_* settings in README.md match your setup.")
        print(f"Details: {exc}")
        sys.exit(1)
    except psycopg2.Error as exc:
        # Any other database error, e.g. the students table hasn't been
        # created yet (run db/02_create_table_and_seed.sql first).
        print(f"Database error: {exc}")
        sys.exit(1)
    except KeyboardInterrupt:
        print("\nStopped by user.")


if __name__ == "__main__":
    main()
